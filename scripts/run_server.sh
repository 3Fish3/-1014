#!/usr/bin/env bash
# ==============================================================================
# 本地 3D 教学系统离线静态 HTTP 服务器启动脚本 (run_server.sh)
# 用于讲师在本地笔记本或教室投影电脑上离线演练与全屏演示。
# ==============================================================================

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WEB_DIR="$DIR/web"
PORT="${1:-8080}"

# 检查端口是否被占用，自动递增寻找可用端口
while ss -tuln | grep -q ":$PORT "; do
    echo "⚠️ 端口 $PORT 已被占用，尝试端口 $((PORT + 1))..."
    PORT=$((PORT + 1))
done

echo "======================================================================"
echo "🚀 启动 RoboMaster 电控三维教学系统本地离线演示服务器"
echo "======================================================================"
echo "📂 Web 根目录: $WEB_DIR"
echo "🌐 访问地址:   http://localhost:$PORT"
echo "🔍 整车全貌:   http://localhost:$PORT/viewer_full.html"
echo "⌨️ 演示快捷键: [→/空格] 下一步  [←] 上一步  [R] 重播本步骤  [F11] 全屏"
echo "🛑 退出服务:   按下 Ctrl + C 即可终止"
echo "======================================================================"

exec python3 -m http.server "$PORT" --directory "$WEB_DIR"
